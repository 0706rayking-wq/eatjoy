const assert = require('node:assert/strict');
const {windowFor,update,personId} = require('../lib/schedule-intent');
const now = Date.parse('2026-11-20T23:59:59+08:00');
assert.equal(windowFor(now).open,true);
assert.equal(windowFor(now+1000).open,false);
assert.equal(windowFor(Date.parse('2026-12-01T00:00:00+08:00')).month,'2027-01');
const b={date:'2026-12-05',kind:'off'},a={id:'a',name:'甲'},c={id:'b',name:'乙'};
let rows=update([],a,b,now-2000);rows=update(rows,c,b,now-1000);
assert.equal(update(rows,a,b,now)[0].submittedAt,now-2000);
rows=update(rows,a,{...b,kind:'clear'},now-500);rows=update(rows,a,b,now);
assert.equal(rows[0].id,'b');assert.equal(rows[1].id,'a');
assert.throws(()=>update([],a,b,now+1000));
assert.throws(()=>update([],a,{...b,date:'2026-12-32'},now));
assert.throws(()=>update([],a,{...b,kind:'available',slots:[{start:'14:00',end:'10:00'}]},now));
assert.throws(()=>update([],a,{...b,kind:'available',slots:[{start:'10:00',end:'14:00'},{start:'13:00',end:'18:00'}]},now));
assert.equal(update([],a,{...b,kind:'available',slots:[{start:'10:00',end:'14:00'},{start:'17:00',end:'22:00'}]},now)[0].slots.length,2);
assert.equal(personId('0912345678').length,24);
console.log('Schedule intent logic: passed');
